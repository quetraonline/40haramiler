create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  event_date timestamptz not null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username, role)
  values (new.id, coalesce(nullif(new.raw_user_meta_data->>'username',''), split_part(new.email,'@',1)), 'member');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.announcements enable row level security;
alter table public.events enable row level security;

drop policy if exists "profiles read authenticated" on public.profiles;
create policy "profiles read authenticated" on public.profiles for select to authenticated using (true);
drop policy if exists "profile update own username" on public.profiles;
create policy "profile update own username" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
revoke update on public.profiles from authenticated;
grant update (username) on public.profiles to authenticated;

drop policy if exists "announcements public read" on public.announcements;
create policy "announcements public read" on public.announcements for select using (true);
drop policy if exists "announcements admin insert" on public.announcements;
create policy "announcements admin insert" on public.announcements for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "announcements admin update" on public.announcements;
create policy "announcements admin update" on public.announcements for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "announcements admin delete" on public.announcements;
create policy "announcements admin delete" on public.announcements for delete to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "events public read" on public.events;
create policy "events public read" on public.events for select using (true);
drop policy if exists "events admin insert" on public.events;
create policy "events admin insert" on public.events for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "events admin update" on public.events;
create policy "events admin update" on public.events for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "events admin delete" on public.events;
create policy "events admin delete" on public.events for delete to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

